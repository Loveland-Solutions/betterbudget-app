/// The scheme kept under [id]; the default for anything else.
Scheme schemeById(String? id) =>
    schemes.firstWhere((s) => s.id == id, orElse: () => defaultScheme);

String schemeGroupName(Words t, SchemeGroup g) => switch (g) {
  SchemeGroup.monochromatic => t.schemeGroupMonochromatic,
  SchemeGroup.romantic => t.schemeGroupRomantic,
  SchemeGroup.playful => t.schemeGroupPlayful,
  SchemeGroup.vibrant => t.schemeGroupVibrant,
  SchemeGroup.neutral => t.schemeGroupNeutral,
  SchemeGroup.tranquil => t.schemeGroupTranquil,
  SchemeGroup.seasonal => t.schemeGroupSeasonal,
};


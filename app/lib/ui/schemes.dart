// The color schemes Settings → Appearance offers: the app's own, then
// the 100 combinations in Figma's resource library
// (figma.com/resource-library/color-combinations), in its groups and order.
// The hex codes are the ones printed on each palette; two printed codes
// don't match their swatch ("#CC550" in Golden hour, "#00F0FF" under
// Bubblegum pop's pale cyan), so those two are the swatch's color.
// Nothing is fetched: the colors are here.
import 'package:flutter/painting.dart';

import 'language.dart';

/// Figma's groups of combinations.
enum SchemeGroup {
  monochromatic,
  romantic,
  playful,
  vibrant,
  neutral,
  tranquil,
  seasonal,
}

/// Four colors and a name. [Palette.of] turns them into the app's colors.
class Scheme {
  const Scheme(this.id, this.group, this.colors);

  /// Kept in the appearance file.
  final String id;

  /// Null for the app's own.
  final SchemeGroup? group;
  final List<Color> colors;
}

